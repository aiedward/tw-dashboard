import sys, time; sys.stdout.reconfigure(encoding="utf-8")
from backend.config import load_universe_cfg
from backend.data import update_all
t=time.time()
cfg=load_universe_cfg()
d=update_all(cfg, mode="watchlist")
print("universe", d["universe"][["code","name","industry","mcap_rank","tags"]].to_string())
px=d["prices"]; print("prices rows", len(px), px.groupby("code")["date"].agg(["min","max","count"]).to_string())
print(px[px.code=="2330"].tail(3).to_string())
print("chips", d["chips"].shape, d["chips"]["date"].nunique(), d["chips"][d["chips"].code=="2330"].tail(3).to_string())
print("qfiis", d["qfiis"][d["qfiis"].code=="2330"].to_string())
print("fund", d["fund"][d["fund"].code.isin(["2330","2317"])].to_string())
for k,v in d["market"].items(): print("mkt",k, v.shape, v.tail(2).to_string() if not v.empty else "")
for k,v in d["events"].items(): print("evt",k,v.shape)
print("elapsed", round(time.time()-t))
